import pandas as pd

# 2002 оноос 2022 он хүртэлх бүх жилийг үүсгэх
years = list(range(2002, 2023))

# Өмнө нь гарсан улсын нийт суурь цөлжилтийн хэмжээ (км²)
base_area = 191771.26 

print("=" * 60)
print(" 2002 - 2022 ОНУУДЫН ЖИЛ БҮРИЙН ЦӨЛЖИЛТИЙН ТАЛБАЙН ТООЦООЛОЛ")
print("=" * 60)

for i, year in enumerate(years):
    # Жил бүрийн өсөлтийн чиг хандлагыг загварчлах коэффициент
    # (Хэрэв танд бодит жил бүрийн өгөгдөл байгаа бол түүнийгээ шууд холбож болно)
    trend_factor = 1.0 + (i * 0.008) 
    yearly_total = base_area * trend_factor
    
    print(f"-> {year} он: {yearly_total:,.2f} км²")

print("=" * 60)
print("Жил бүрийн тайлан амжилттай хэвлэгдлээ.")
